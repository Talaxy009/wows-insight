}

@Composable
fun ErrorState(
    title: String,
    message: UiText,
    onRetry: () -> Unit,
    modifier: Modifier = Modifier,
) {
    EmptyState(
        icon = Icons.Outlined.ErrorOutline,
        title = title,
        message = message.resolve(),
        modifier = modifier,
        action = {
            FilledTonalButton(onClick = onRetry) {
                Text(stringResource(R.string.common_retry))
            }
        },
    )
}

